# Integer (int) - Whole numbers
age = 23
print("Age:", age, "Type:", type(age))

# Float - Decimal numbers
height = 5.9
print("Height:", height, "Type:", type(height))

# String (str) - Text data
name = "John"
print("Name:", name, "Type:", type(name))

# Boolean (bool) - True or False
is_student = True
print("Is Student:", is_student, "Type:", type(is_student))

# List - A collection of items, ordered and mutable
fruits = ["apple", "banana", "cherry"]
print("Fruits:", fruits, "Type:", type(fruits))

# Tuple - A collection of items, ordered but immutable
coordinates = (10, 20)
print("Coordinates:", coordinates, "Type:", type(coordinates))

# Dictionary (dict) - A collection of key-value pairs
person = {"name": "Alice", "age": 25}
print("Person:", person, "Type:", type(person))

# Set - A collection of unique items (unordered)
unique_numbers = {1, 2, 3, 4, 5}
print("Unique Numbers:", unique_numbers, "Type:", type(unique_numbers))

# NoneType - Represents a null or no value
nothing = None
print("Nothing:", nothing, "Type:", type(nothing))
